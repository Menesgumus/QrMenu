#!/usr/bin/env node
/**
 * Pure-Node build-time image manifest generator & verifier.
 *
 * Emits a compact per-slug tuple table into src/data/image-asset-manifest.ts so
 * client bundles stay minimal while --verify still enforces every file's 8-char
 * SHA-256 content hash and exact WebP pixel dimensions.
 *
 * Tuple format per slug:
 *   [iconHash, thumbsHash, cardHash, gridHash, cardLgHash, cardLgSize, detailMdHash, detailMdH, fullHash, fullW, fullH]
 */

import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";

const ROOT = process.cwd();
const MENU_IMAGES_DIR = path.join(ROOT, "public", "images", "menu");
const HASHED_DIR = path.join(MENU_IMAGES_DIR, "hashed");
const MANIFEST_PATH = path.join(ROOT, "src", "data", "image-asset-manifest.ts");

const VARIANTS = [
  "icon",
  "thumbs",
  "card",
  "grid",
  "card-lg",
  "detail-md",
  "full",
];

const FIXED_VARIANT_DIMS = {
  icon: { width: 144, height: 144 },
  thumbs: { width: 208, height: 208 },
  card: { width: 360, height: 360 },
  grid: { width: 480, height: 480 },
};

function readWebpDimensions(buf, filePath) {
  if (
    buf.length < 30 ||
    buf.toString("ascii", 0, 4) !== "RIFF" ||
    buf.toString("ascii", 8, 12) !== "WEBP"
  ) {
    throw new Error(`Invalid WebP header: ${filePath}`);
  }

  let offset = 12;
  while (offset + 8 <= buf.length) {
    const chunkId = buf.toString("ascii", offset, offset + 4);
    const chunkSize = buf.readUInt32LE(offset + 4);
    const dataOffset = offset + 8;

    if (chunkId === "VP8X" && dataOffset + 10 <= buf.length) {
      const w = 1 + (buf[dataOffset + 4] | (buf[dataOffset + 5] << 8) | (buf[dataOffset + 6] << 16));
      const h = 1 + (buf[dataOffset + 7] | (buf[dataOffset + 8] << 8) | (buf[dataOffset + 9] << 16));
      return { width: w, height: h };
    }

    if (chunkId === "VP8L" && dataOffset + 5 <= buf.length) {
      const b0 = buf[dataOffset + 1];
      const b1 = buf[dataOffset + 2];
      const b2 = buf[dataOffset + 3];
      const b3 = buf[dataOffset + 4];
      const w = 1 + (((b1 & 0x3f) << 8) | b0);
      const h = 1 + (((b3 & 0x0f) << 10) | (b2 << 2) | ((b1 & 0xc0) >> 6));
      return { width: w, height: h };
    }

    if (chunkId === "VP8 " && dataOffset + 10 <= buf.length) {
      if (
        buf[dataOffset + 3] === 0x9d &&
        buf[dataOffset + 4] === 0x01 &&
        buf[dataOffset + 5] === 0x2a
      ) {
        const w = buf.readUInt16LE(dataOffset + 6) & 0x3fff;
        const h = buf.readUInt16LE(dataOffset + 8) & 0x3fff;
        return { width: w, height: h };
      }
    }

    offset = dataOffset + chunkSize + (chunkSize % 2);
  }

  throw new Error(`Could not determine WebP dimensions: ${filePath}`);
}

function scanDiskAssets(baseDir = MENU_IMAGES_DIR) {
  const byKey = new Map();
  const slugs = new Set();

  for (const variant of VARIANTS) {
    const dir = path.join(baseDir, variant);
    if (!fs.existsSync(dir)) {
      throw new Error(`Missing variant directory: ${dir}`);
    }
    const files = fs
      .readdirSync(dir)
      .filter((name) => name.endsWith(".webp"))
      .sort();
    for (const fileName of files) {
      const absPath = path.join(dir, fileName);
      const buf = fs.readFileSync(absPath);
      const hash = crypto.createHash("sha256").update(buf).digest("hex").slice(0, 8);
      const { width, height } = readWebpDimensions(buf, absPath);
      const slug = fileName.slice(0, -".webp".length);
      slugs.add(slug);
      byKey.set(`${variant}/${slug}`, {
        key: `${variant}/${slug}`,
        variant,
        slug,
        absPath,
        hash,
        width,
        height,
      });
    }
  }
  return { byKey, slugs: [...slugs].sort() };
}

function formatManifestModule({ byKey, slugs }) {
  const lines = [
    "// AUTO-GENERATED BY scripts/sync-image-manifest.mjs — DO NOT EDIT MANUALLY.",
    "// Run `pnpm images:sync` after updating any file in public/images/menu/.",
    "",
    "// Tuple order:",
    "// [0:iconHash, 1:thumbsHash, 2:cardHash, 3:gridHash, 4:cardLgHash, 5:cardLgSize, 6:detailMdHash, 7:detailMdH, 8:fullHash, 9:fullW, 10:fullH]",
    "export type CompactImageAssetTuple = readonly [",
    "  string,",
    "  string,",
    "  string,",
    "  string,",
    "  string,",
    "  number,",
    "  string,",
    "  number,",
    "  string,",
    "  number,",
    "  number,",
    "];",
    "",
    "export const IMAGE_ASSET_MANIFEST: Record<string, CompactImageAssetTuple> = {",
  ];

  for (const slug of slugs) {
    const icon = byKey.get(`icon/${slug}`);
    const thumbs = byKey.get(`thumbs/${slug}`);
    const card = byKey.get(`card/${slug}`);
    const grid = byKey.get(`grid/${slug}`);
    const cardLg = byKey.get(`card-lg/${slug}`);
    const detailMd = byKey.get(`detail-md/${slug}`);
    const full = byKey.get(`full/${slug}`);

    for (const [v, rec] of Object.entries(FIXED_VARIANT_DIMS)) {
      const asset = byKey.get(`${v}/${slug}`);
      if (asset && (asset.width !== rec.width || asset.height !== rec.height)) {
        throw new Error(
          `Unexpected ${v} dimensions for ${slug}: got ${asset.width}x${asset.height}, expected ${rec.width}x${rec.height}`
        );
      }
    }
    if (cardLg && cardLg.width !== cardLg.height) {
      throw new Error(`Expected square card-lg for ${slug}, got ${cardLg.width}x${cardLg.height}`);
    }
    if (detailMd && detailMd.width !== 640) {
      throw new Error(`Expected width=640 detail-md for ${slug}, got ${detailMd.width}`);
    }

    const tuple = [
      icon?.hash ?? "",
      thumbs?.hash ?? "",
      card?.hash ?? "",
      grid?.hash ?? "",
      cardLg?.hash ?? "",
      cardLg?.width ?? 0,
      detailMd?.hash ?? "",
      detailMd?.height ?? 0,
      full?.hash ?? "",
      full?.width ?? 0,
      full?.height ?? 0,
    ];
    lines.push(`  ${JSON.stringify(slug)}: ${JSON.stringify(tuple)},`);
  }

  lines.push("};", "");
  return lines.join("\n");
}

function materializeHashedFiles(byKey) {
  fs.rmSync(HASHED_DIR, { recursive: true, force: true });
  for (const entry of byKey.values()) {
    const targetDir = path.join(HASHED_DIR, entry.variant);
    fs.mkdirSync(targetDir, { recursive: true });
    const targetFile = path.join(targetDir, `${entry.slug}.${entry.hash}.webp`);
    fs.copyFileSync(entry.absPath, targetFile);
  }
}

function parseExistingManifest(manifestFile = MANIFEST_PATH) {
  if (!fs.existsSync(manifestFile)) {
    throw new Error(`Missing manifest file: ${manifestFile}. Run pnpm images:sync`);
  }
  const src = fs.readFileSync(manifestFile, "utf8");
  const expectedByKey = new Map();
  const re = /^\s*"([^"]+)":\s*(\[[^\]]+\]),?\s*$/gm;
  let match;
  while ((match = re.exec(src)) !== null) {
    const slug = match[1];
    const tuple = JSON.parse(match[2]);
    const [
      iconHash,
      thumbsHash,
      cardHash,
      gridHash,
      cardLgHash,
      cardLgSize,
      detailMdHash,
      detailMdH,
      fullHash,
      fullW,
      fullH,
    ] = tuple;

    if (iconHash) expectedByKey.set(`icon/${slug}`, { hash: iconHash, width: 144, height: 144 });
    if (thumbsHash) expectedByKey.set(`thumbs/${slug}`, { hash: thumbsHash, width: 208, height: 208 });
    if (cardHash) expectedByKey.set(`card/${slug}`, { hash: cardHash, width: 360, height: 360 });
    if (gridHash) expectedByKey.set(`grid/${slug}`, { hash: gridHash, width: 480, height: 480 });
    if (cardLgHash) expectedByKey.set(`card-lg/${slug}`, { hash: cardLgHash, width: cardLgSize, height: cardLgSize });
    if (detailMdHash) expectedByKey.set(`detail-md/${slug}`, { hash: detailMdHash, width: 640, height: detailMdH });
    if (fullHash) expectedByKey.set(`full/${slug}`, { hash: fullHash, width: fullW, height: fullH });
  }
  if (expectedByKey.size === 0) {
    throw new Error(`Manifest parsed 0 entries: ${manifestFile}`);
  }
  return expectedByKey;
}

function verifyManifest(byKey, expectedByKey) {
  const errors = [];

  for (const [key, disk] of byKey.entries()) {
    const rec = expectedByKey.get(key);
    if (!rec) {
      errors.push(`Missing in manifest (new/unregistered file): ${key}`);
      continue;
    }
    if (rec.hash !== disk.hash) {
      errors.push(`Content hash mismatch for ${key}: manifest=${rec.hash} disk=${disk.hash}`);
    }
    if (rec.width !== disk.width || rec.height !== disk.height) {
      errors.push(
        `Dimension mismatch for ${key}: manifest=${rec.width}x${rec.height} disk=${disk.width}x${disk.height}`
      );
    }
  }

  for (const key of expectedByKey.keys()) {
    if (!byKey.has(key)) {
      errors.push(`Stale manifest entry (file missing on disk): ${key}`);
    }
  }

  return errors;
}

const args = new Set(process.argv.slice(2));
const modeWrite = args.has("--write");
const modeVerify = args.has("--verify");

if (!modeWrite && !modeVerify) {
  console.error("Usage: node scripts/sync-image-manifest.mjs --write | --verify");
  process.exit(2);
}

const scanned = scanDiskAssets();

if (modeWrite) {
  const content = formatManifestModule(scanned);
  fs.writeFileSync(MANIFEST_PATH, content, "utf8");
  materializeHashedFiles(scanned.byKey);
  console.log(
    `[images:sync] Wrote ${scanned.byKey.size} asset checks (${scanned.slugs.length} slugs) to ${path.relative(ROOT, MANIFEST_PATH)} and materialized hashed assets.`
  );
  process.exit(0);
}

if (modeVerify) {
  const expectedByKey = parseExistingManifest();
  const errors = verifyManifest(scanned.byKey, expectedByKey);
  if (errors.length > 0) {
    console.error(`[images:verify] FAILED (${errors.length} issue(s)):`);
    for (const err of errors.slice(0, 20)) {
      console.error(`  - ${err}`);
    }
    if (errors.length > 20) {
      console.error(`  ... and ${errors.length - 20} more.`);
    }
    console.error("Run `pnpm images:sync` to update the manifest and hashed assets.");
    process.exit(1);
  }
  materializeHashedFiles(scanned.byKey);
  console.log(`[images:verify] OK (${scanned.byKey.size} assets verified, hashed directory synced).`);
}
